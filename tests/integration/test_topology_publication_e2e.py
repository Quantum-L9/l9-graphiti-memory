@pytest.fixture(scope="module")
def topology_bundle():
    return load_verified_bundle(FIXTURE_ROOT / "topology-bundle")


@pytest.fixture
def principal() -> MemoryPrincipal:
    return MemoryPrincipal(
        principal_id="topology-operator",
        tenant_id="tenant-constellation",
        read_namespaces=NAMESPACES,
        write_namespaces=NAMESPACES,
    )


