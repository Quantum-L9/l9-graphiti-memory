"""Canonical E2E qualification against the exact bound Topology plan.

The fixture bundles under ``tests/fixtures/topology_publication`` were
generated by the producer's own compiler and plan builder at the bound
l9-constellation-topology PR #18 head (see PROVENANCE.md there). No network
effect exists anywhere in these stages: canonical writes land in a temporary
SQLite store behind a null projection, and Gate is consulted only through its
static intent validator.
"""

